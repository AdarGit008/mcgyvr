"""A catalog mixture of experts is sized as one, alike from either list.

A catalog record states the `architecture` of its weights (`dense` or `moe`),
read from its file's header by the law placement reads a header by
(`record.architecture_of`: expert blocks ``--n-cpu-moe`` can move). A Hub
read fills it; the shipped catalog states it for every record, regenerated by
``make catalog`` from the shipped header rows; a cache written before records
carried it keeps the shipped record's. Setup and the ladder size an `moe`
record as a mixture of experts, from its file's header row, and a capability
table MoE row whose `model_id` names that record is sized from the same row,
so the same model fits the same way by whichever list it came from.

The machines are invented; the models are the shipped catalog's own records.
"""

from __future__ import annotations

import copy
import json
from dataclasses import replace
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest

from mcgyvr.capability import load
from mcgyvr.cli import sizing
from mcgyvr.config import Config, Ladder, Unit
from mcgyvr.knowledge import geometry, hub, regenerate
from mcgyvr.knowledge import record as kr
from mcgyvr.knowledge import store as ks
from mcgyvr.scan import Scan
from mcgyvr.serving import Unit as ServedUnit
from mcgyvr.serving import UnitError, fetchlist, units_for
from tests import hub_recorded as hr
from tests.table_fixture import row, table_document, write_table

MIXTURE = "Qwen/Qwen3-30B-A3B"
DENSE = "Qwen/Qwen3-8B"


def _shipped(model_id: str) -> kr.ModelRecord:
    return next(r for r in ks.shipped() if r.model_id == model_id)


def _raw(model_id: str) -> dict[str, Any]:
    raw = json.loads(ks.catalog_path().read_text(encoding="utf-8"))
    entry: dict[str, Any] = next(m for m in raw["models"] if m["model_id"] == model_id)
    return copy.deepcopy(entry)


def _document(*entries: dict[str, Any]) -> dict[str, Any]:
    return {"schema_version": kr.SCHEMA_VERSION, "models": list(entries)}


def _scan(vram_mib: int) -> Scan:
    return Scan.of(
        host="rig.example",
        vram_mib=vram_mib,
        ram_gb=64.0,
        disk_free_gb=900.0,
        cores=8,
        threads=16,
        bandwidth_gbps=41.2,
    )


def _unit(model: str, vram_mib: int = 12288) -> ServedUnit:
    config = Config(
        path=None,
        data={},
        units={
            "rung": Unit(name="rung", address="http://rig.example:8080", model=model)
        },
        ladder=Ladder(names=("rung",)),
    )
    (unit,) = units_for(
        config,
        {"rig.example": _scan(vram_mib)},
        specs=sizing._model_specs(),
        ctx_per_slot=4096,
    )
    return unit


# --- the record ---------------------------------------------------------------


def test_every_shipped_record_states_the_architecture_its_header_row_reads() -> None:
    rows = geometry.load()
    for one in ks.shipped():
        found = rows.of(one.weights)
        assert found is not None, one.model_id
        assert one.architecture == kr.architecture_of(found.row), one.model_id
    assert {one.architecture for one in ks.shipped()} == set(kr.ARCHITECTURES)


def test_the_shipped_catalog_is_what_make_catalog_writes() -> None:
    assert regenerate.main(["--check"]) == 0


def test_a_shipped_record_that_states_no_architecture_is_refused() -> None:
    entry = _raw(DENSE)
    del entry["architecture"]
    with pytest.raises(kr.KnowledgeError, match="states no architecture"):
        kr.parse_document(_document(entry), "shipped", shipped=True)
    (one,) = kr.parse_document(_document(entry), "cache", shipped=False)
    assert one.architecture is None


def test_an_architecture_outside_the_vocabulary_is_refused() -> None:
    entry = _raw(DENSE) | {"architecture": "hybrid"}
    with pytest.raises(kr.KnowledgeError, match="architecture 'hybrid'"):
        kr.parse_document(_document(entry), "cache", shipped=False)


def test_the_architecture_round_trips_through_the_cache_writer() -> None:
    one = _shipped(MIXTURE)
    (back,) = kr.parse_document(
        json.loads(ks.write(one).read_text(encoding="utf-8")), "cache", shipped=False
    )
    assert back.architecture == kr.MOE


def test_a_cache_written_before_the_field_keeps_the_shipped_architecture() -> None:
    entry = _raw(MIXTURE)
    del entry["architecture"]
    target = ks.cache_file(entry["model_id"], entry["quant"])
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(_document(entry)), encoding="utf-8")
    known = {k.record.model_id: k for k in ks.offline().known}[MIXTURE]
    assert known.origin == ks.CACHE
    assert known.record.architecture == kr.MOE


def test_a_hub_read_files_each_record_with_its_headers_architecture(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    hr.install(monkeypatch)
    answer = hub.candidates(hub.CODE, max_bytes=hr.ROOMIEST, today=hr.DAY)
    assert answer.records
    rows = geometry.load()
    for one in answer.records:
        found = rows.of(one.weights)
        assert found is not None
        assert one.architecture == kr.architecture_of(found.row)


def test_the_header_law_is_the_expert_blocks_placement_moves() -> None:
    assert kr.architecture_of({"placeable_blocks": [3, 4]}) == kr.MOE
    assert kr.architecture_of({"placeable_blocks": []}) == kr.DENSE
    assert kr.architecture_of({}) == kr.DENSE


# --- sizing -------------------------------------------------------------------


def test_an_moe_record_is_sized_from_its_files_header_row() -> None:
    specs = {s.name: s for s in sizing._catalog_specs()}
    record = _shipped(MIXTURE)
    spec = specs[MIXTURE]
    found = geometry.load().of(record.weights)
    assert found is not None
    assert spec.moe is True
    assert spec.geometry is not None
    assert spec.geometry["file"] == fetchlist._weights_file_name(MIXTURE)
    assert {k: v for k, v in spec.geometry.items() if k != "file"} == {
        k: v for k, v in found.row.items() if k != "file"
    }
    assert specs[DENSE].moe is False and specs[DENSE].geometry is None


def test_an_moe_record_spills_experts_to_the_host_where_dense_it_did_not_fit() -> None:
    """On an invented 12 GiB card the 17 GiB mixture's file alone overflows the
    card, so sized as dense it was refused; sized as an MoE its experts spill to
    the host's RAM and it is placed."""
    unit = _unit(MIXTURE)
    assert unit.fit.fits is True
    assert unit.fit.ram_gb > 0
    assert unit.fit.vram_gb < 12.0


def test_an_moe_record_without_a_header_row_is_refused_not_sized_dense(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    record = replace(_shipped(MIXTURE), weights=None)
    monkeypatch.setattr(ks, "offline", lambda: SimpleNamespace(records=(record,)))
    (spec,) = sizing._catalog_specs()
    assert spec.moe is True and spec.geometry is None
    with pytest.raises(UnitError, match="sizing an MoE needs its geometry"):
        _unit(MIXTURE)


def test_an_moe_catalog_row_and_its_capability_table_twin_agree(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """An invented table row naming the shipped mixture by `model_id` is sized
    from the record's header row under both its names, so it is placed exactly
    as the catalog record alone is."""
    alone = _unit(MIXTURE)
    record = _shipped(MIXTURE)
    twin = {
        **row(
            "invented-mixture:30b",
            architecture="moe",
            weights_gb=record.size_bytes.value / 1e9,
            vram_gb_working=3.0,
        ),
        "model_id": MIXTURE,
    }
    table = load(write_table(tmp_path, table_document(rows=[twin])))
    monkeypatch.setattr(sizing, "load", lambda: table)
    specs = {s.name: s for s in sizing._model_specs()}
    for name in (MIXTURE, "invented-mixture:30b"):
        assert specs[name].moe is True
        assert specs[name].geometry is not None
    by_id = _unit(MIXTURE)
    by_table = _unit("invented-mixture:30b")
    for unit in (by_id, by_table):
        assert unit.fit.fits is True
        assert unit.fit.vram_gb == alone.fit.vram_gb
        assert unit.fit.ram_gb == alone.fit.ram_gb
        assert unit.args.get("--n-cpu-moe") == alone.args.get("--n-cpu-moe")
    assert alone.args.get("--n-cpu-moe")
