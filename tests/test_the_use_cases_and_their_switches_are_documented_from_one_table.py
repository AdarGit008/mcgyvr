"""The use cases and every switch are documented from the one table in config.py.

SETUP.md carries a section rendered from `SWITCHES`: each point where mcgyvr
shapes what a model is sent or what comes back, the policy key that switches
it, and what off means, with the four knobs mcgyvr-code exposes called by their plain
names. `/mcgyvr-use` is a skill of its own, generated by docgen and pinned by
`make docs-check` like the others.
"""

from __future__ import annotations

from mcgyvr import docgen
from mcgyvr.config import SWITCHES, USE_CASES
from tests._paths import REPO

KNOBS = (
    "ladder vs single model",
    "Jev unit on/off",
    "repair on/off",
    "attempts per rung and escalation",
)


def test_setup_md_names_every_switch_key_and_the_four_knobs() -> None:
    rendered = docgen.render_setup()

    assert "## Use cases and switches" in rendered
    for switch in SWITCHES:
        for key in switch.keys:
            assert f"`{key}`" in rendered, key
    for knob in KNOBS:
        assert knob in rendered, knob
    for name in USE_CASES:
        assert f"`{name}`" in rendered


def test_the_use_skill_is_generated_and_committed_as_rendered() -> None:
    rendered = docgen.render_use_skill()
    committed = (REPO / docgen.USE_SKILL_PATH).read_text(encoding="utf-8")

    assert committed == rendered
    assert rendered.startswith("---\nname: mcgyvr-use\n")
    assert "mcgyvr use" in rendered
    for name in USE_CASES:
        assert f"`{name}`" in rendered


def test_no_generated_line_is_longer_than_the_house_limit() -> None:
    for text in (docgen.render_setup(), docgen.render_use_skill()):
        section = text.split("## Use cases and switches", 1)[-1].split("\n## ", 1)[0]
        assert all(len(line) <= 105 for line in section.splitlines())
