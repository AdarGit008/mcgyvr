def test_nothing_outside_the_writer_names_the_file() -> None:
    """The acceptance property that is about the guard path, not the content.

    A field in this block is comprehensive *because* nobody admitted it. Wiring
    a guard to one would be a comparison on an unadmitted field — the failure
    ADR-0027 D7 separates the two blocks to prevent — so the check is that the
    name does not spread, and the allow-list above is the thing a future lane
    has to argue with.
    """
    found = subprocess.run(
        ["git", "grep", "-l", "observed.json", "--", "src/", "tools/", "tests/"],
        cwd=REPO,
        capture_output=True,
        text=True,
    )
    named = {line for line in found.stdout.splitlines() if line}
    assert named <= NAMES_THE_FILE, (
        f"{sorted(named - NAMES_THE_FILE)} name observed.json. Nothing reads "
        "this block for comparison (ADR-0027 D7): a field in it is "
        "comprehensive because nobody admitted it, and promotion into "
        "identity.KEY is the owner's."
    )


def test_the_contract_module_records_the_landed_state(observed: Any) -> None:
    """#286's item 7: the four say what is true now, and did not move to #276's.

    `AWAITING_ADMISSION` means "#276's rule has not admitted it". #276's rule is
    not these fields' promotion path — D7 is — so they get their own reason
    rather than being folded into a queue they are not in.
    """
    identity = observed.identity
    for field in observed.PROBE_SET:
        assert identity.PENDING_REASON[field] == identity.CAPTURED_IN_OBSERVED
        assert field in identity.RECORDED
        assert field not in identity.KEY
    assert not hasattr(identity, "AWAITING_PROBE_SET"), (
        "the third state is gone: nothing in the repository is waiting on a "
        "writer for these four any more."
    )
