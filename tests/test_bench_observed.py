def _endpoint(
    observed: Any,
    monkeypatch: pytest.MonkeyPatch,
    tags: Any,
    show: Any,
    *,
    ps: Any = None,
    models: Any = None,
    version: Any = None,
    server_info: Any = None,
    metrics: str | None = None,
) -> None:
    """A server, without one — routed by URL, through the module's own seams.

    Routed rather than answered flat because the engine is identified from
    *which* calls come back: a fake that returned the same document to
    ``/api/tags`` and ``/v1/models`` would make every arm look like ollama, and
    the dispatch this file exists to test would never run.
    """
    table = {
        "/api/tags": tags,
        "/api/ps": ps,
        "/api/version": version if tags is not None else None,
        "/v1/models": models,
        "/version": version if tags is None else None,
        "/server_info": server_info,
    }

    def get(url: str, *, timeout: float) -> Any:
        for path, answer in table.items():
            if url.endswith(path):
                return answer
        return None

    monkeypatch.setattr(observed.identity, "_get_json", get, raising=True)
    monkeypatch.setattr(
        observed.identity, "_post_json", lambda url, body, *, timeout: show
    )
    monkeypatch.setattr(
        observed, "_get_text", lambda url, *, timeout: metrics, raising=True
    )


